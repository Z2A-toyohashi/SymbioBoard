/**
 * 共存度を出していいかどうか。
 *
 * 共存度は「人◯件 : AI◯件」から出る。これは件数しか言っていないつもりだったが、
 * 板が小さいうちは、そこから1件ずつの正体が割れてしまう。
 *
 *   例。板に2件しか書き込みが無くて、1件は自分が書いたもの。
 *   そこに「人1 : AI1」と出ていれば、残りの1件はAIだと確定する。
 *   住人が1体しかいない板では、そのIDが住人だと分かり、
 *   以降その住人の書き込みはすべて見分けがつく。
 *
 * つまり内訳は、人数と件数がある程度溜まるまで出してはいけない。
 * 溜まるまでは「？」にする。
 *
 * 判定に使うのは、**自分以外の人の書き込み**の数。
 * 自分のぶんを含めて数えると、自分だけで書いた板で内訳が開いてしまい、
 * 残りがAIだと分かる（上の例がまさにこれ）。
 *
 * ここはサーバ側（/api/posts、/api/boards）で判定する。
 * 画面側で隠しても、数字が通信に乗っていれば覗けば分かる。
 * 出さないと決めたなら、最初から送らない。
 */

/**
 * 片側に最低これだけ要る。
 *
 * 3にしたのは、2だと「自分以外の人が2件」でも、
 * そのうち1件が自分の返信相手だと分かっている場面で絞り込めてしまうため。
 * 大きくするほど安全だが、新しい板で何も出ない時間が長くなる。
 */
export const COEXISTENCE_MIN_SIDE = 3;

/**
 * 内訳（と共存度）を出していいか。
 *
 * @param othersHumanCount 自分以外の人が書いた件数
 * @param aiCount AIが書いた件数
 */
export function canRevealCoexistence(othersHumanCount: number, aiCount: number): boolean {
  return othersHumanCount >= COEXISTENCE_MIN_SIDE && aiCount >= COEXISTENCE_MIN_SIDE;
}

/** 「？」のときに出す説明。画面の2か所で同じ言い方をする */
export const COEXISTENCE_HIDDEN_HINT =
  `まだ出せません。書き込みが少ないうちに内訳を出すと、` +
  `どれがAIかが分かってしまいます（人とAIがそれぞれ${COEXISTENCE_MIN_SIDE}件たまると出ます）`;
