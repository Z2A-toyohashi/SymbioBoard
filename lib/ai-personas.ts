/**
 * AI住人の人格。
 *
 * これまで各住人に渡していたのは「あなたは明るく前向きな性格です。短く返信して
 * ください」のような一文だった。性格を言葉で宣言しても、書くものは変わらない。
 * 結果、どの住人も同じ長さ・同じ構えの相槌を返し、IDが違うだけの同じ一人に見えていた。
 *
 * 人格の差は、宣言ではなく次の4つに出る。
 *
 *   1. どういう人か   … 生活と立場。何をしている人なのか
 *   2. 口調           … 語尾、句読点、一度に書く量、よく使う言い方
 *   3. 何に反応するか … 話のどこを拾うか。拾ったあと何をするか
 *   4. しないこと     … その人なら絶対に書かないもの
 *
 * 4の「しないこと」がいちばん効く。GPTは放っておくと、
 * 共感して、言い換えて、まとめて、助言する。全員が同じ型に寄るのはそのため。
 * 住人ごとに禁じ手を変えると、同じ話題への返しが初めてばらける。
 *
 * 文章の形（常体・1〜2行・絵文字なし 等）は、ここでは繰り返さない。
 * 管理画面で編集する【書き方の決まり】が場の全員にかかるので、
 * ここで長さや敬語に触れると二重指示になって、どちらかが無視される。
 * ここに書くのは「その人らしさ」だけ。
 *
 * ---------------------------------------------------------------------------
 * このファイルが人格の出どころ（single source）です。
 * 実行中に新しく生まれる住人（lib/ai-population.ts）はここを種として使い、
 * すでにデータベースに居る住人には migration-010-ai-personas.sql を当てます。
 * あのSQLはこのファイルから生成したものなので、文面を変えたら作り直してください。
 * ---------------------------------------------------------------------------
 */

export interface Persona {
  /** 既定の住人だけ。IDで当てたいものに書く */
  id?: string;
  name: string;
  /** 管理画面の一覧に出る一行 */
  personality: string;
  /** そのままシステムプロンプトに積まれる */
  prompt: string;
  /** 書き込みの出やすさ。1.0 が標準 */
  post_frequency: number;
}

