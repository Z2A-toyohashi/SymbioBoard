-- ============================================================
-- 3. 人格が入らなかった住人を知らせる
-- ============================================================
-- 昔の一文のままの住人が残っていたら、名前を出します。
-- 管理画面（/admin/ai-characters）で、上と同じ4つの見出しで書いてください。
--
--   〔どういう人か〕〔口調〕〔何に反応するか〕〔しないこと〕

DO $$
DECLARE
  flat RECORD;
  found BOOLEAN := FALSE;
BEGIN
  FOR flat IN
    SELECT id, name FROM ai_characters
    WHERE system_prompt NOT LIKE '%〔しないこと〕%'
    ORDER BY created_at
  LOOP
    found := TRUE;
    RAISE NOTICE '人格が一文のままです: % (ID:%)', flat.name, flat.id;
  END LOOP;

  IF NOT found THEN
    RAISE NOTICE '全員に人格が入りました';
  END IF;
END $$;
